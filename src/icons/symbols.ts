// Symbol id -> Lucide glyph. Obsidian ships Lucide, so these cost nothing in the bundle: the
// renderer asks Obsidian's `getIcon()` for the glyph by name.
//
// Pattern: a frozen lookup table of candidate names, tried in order. Lucide renames glyphs
// between releases and every Obsidian version pins its own, so a single hard-coded name would
// silently stop resolving; the fallbacks keep an id working across versions.

