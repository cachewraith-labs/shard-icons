/** Lucide names to try for a symbol id, or `null` for an id this build does not know. */
export function symbolGlyphs(id: string): readonly string[] | null {
	return Object.hasOwn(SYMBOLS, id) ? (SYMBOLS[id] ?? null) : null;
}
